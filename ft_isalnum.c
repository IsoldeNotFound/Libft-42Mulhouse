#include "libft.h"

int	ft_isalnum(char *str)
{
	int	i;

	i = 0;
	while (str[i] != '\0')
	{
		if (! (ft_isalpha(str[i]) || ft_isdigit(str[i])))
		{
            return (0);
		}
		i++;
	}
	return (1);
}