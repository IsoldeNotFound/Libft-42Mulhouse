#include "libft.h"

void	ft_lstadd_back(t_list **lst, t_list *new)
{
	t_list	*last;

	last = *lst;
	if (last)
	{
		last = ft_lstlast(*lst);
		last->next = new;
		return ;
	}
	*lst = new;
}
