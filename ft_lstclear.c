#include "libft.h"

void	ft_lstclear(t_list **lst, void (*del)(void *))
{
	t_list	*elem;
	t_list	*next;

	elem = *lst;
	while (elem != NULL)
	{
		next = elem->next;
		ft_lstdelone(elem, del);
		elem = next;
	}
	*lst = NULL;
}
